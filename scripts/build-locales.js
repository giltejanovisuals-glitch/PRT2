/*
 * Build step for the language system (js/i18n.js). Part of `npm run build`.
 *
 * For each data/locales/<code>.json, in menu order:
 *   1. Checks it against en.json — the same keys, the same {placeholders},
 *      the same markup tags, no empty values — and reports anything off.
 *   2. Writes data/locales/<code>.js, the dictionary as a script (loads on
 *      file:// pages too, where browsers block fetch).
 * Then rewrites the LANGUAGES block in js/i18n.js: the menu's languages,
 * each marked published only when its file says
 *   "_meta.status": "reviewed"
 * AND it passed every check. Draft languages are still built, so they can
 * be reviewed on localhost or with ?lang-preview=1, but visitors never see
 * them. A file marked reviewed that fails a check stops the build.
 *
 *   node scripts/build-locales.js            build + report
 *   node scripts/build-locales.js --check    report only, write nothing
 */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "data", "locales");
const I18N_JS = path.join(ROOT, "js", "i18n.js");
const ORDER = ["en", "fil", "es", "zh-CN", "ja", "ko"];
const CHECK_ONLY = process.argv.includes("--check");

const read = (code) => {
  const file = path.join(DIR, `${code}.json`);
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    console.error(`[locales] ${code}.json is not valid JSON: ${error.message}`);
    process.exitCode = 1;
    return null;
  }
};

const placeholders = (text) => [...new Set((String(text).match(/\{\w+\}/g) || []))].sort().join(",");
const tags = (text) => (String(text).match(/<\/?[a-z][a-z0-9]*/gi) || []).map((tag) => tag.toLowerCase()).sort().join(",");
const isMeta = (key) => key.startsWith("_meta.");

const en = read("en");
if (!en) {
  console.error("[locales] data/locales/en.json is missing — it is the source for every other language.");
  process.exit(1);
}
const enKeys = Object.keys(en).filter((key) => !isMeta(key));

// English values that repeat: harmless (the markup uses one key per
// string), but worth knowing when adding copy.
const seen = new Map();
enKeys.forEach((key) => {
  const value = en[key];
  if (/\{\w+\}/.test(value)) return;
  if (seen.has(value)) console.log(`[locales] note: en "${key}" repeats "${seen.get(value)}"`);
  else seen.set(value, key);
});

const languages = [];
const hash = crypto.createHash("sha1");
let failed = false;

ORDER.forEach((code) => {
  const dict = read(code);
  if (!dict) {
    console.warn(`[locales] ${code}: no data/locales/${code}.json — left out of the menu`);
    return;
  }
  const problems = [];
  const missing = enKeys.filter((key) => typeof dict[key] !== "string" || dict[key].trim() === "");
  const extra = Object.keys(dict).filter((key) => !isMeta(key) && !(key in en));
  enKeys.forEach((key) => {
    if (typeof dict[key] !== "string" || !dict[key].trim()) return;
    if (placeholders(dict[key]) !== placeholders(en[key])) problems.push(`${key}: placeholders ${placeholders(dict[key]) || "none"} ≠ English ${placeholders(en[key]) || "none"}`);
    if (tags(dict[key]) !== tags(en[key])) problems.push(`${key}: markup differs from English`);
  });
  ["_meta.name", "_meta.short", "_meta.status"].forEach((key) => {
    if (!dict[key]) problems.push(`${key} is missing`);
  });

  const reviewed = dict["_meta.status"] === "reviewed";
  const complete = !missing.length && !extra.length && !problems.length;
  const published = code === "en" || (reviewed && complete);
  const same = code === "en" ? 0 : enKeys.filter((key) => dict[key] === en[key]).length;

  const summary = `${code}: ${enKeys.length - missing.length}/${enKeys.length} keys` +
    (same ? `, ${same} identical to English` : "") +
    ` — ${published ? "PUBLISHED" : `draft (${dict["_meta.status"] || "no status"})`}`;
  console.log(`[locales] ${summary}`);
  const report = (label, list) => {
    if (!list.length) return;
    console.log(`  ${label} (${list.length}): ${list.slice(0, 12).join(" | ")}${list.length > 12 ? " | …" : ""}`);
  };
  report("missing", missing);
  report("not in en.json", extra);
  report("problems", problems);

  if (reviewed && !complete && code !== "en") {
    console.error(`[locales] ${code} is marked reviewed but is incomplete — fix it or set _meta.status back to "draft".`);
    failed = true;
  }

  const body = JSON.stringify(dict);
  hash.update(code).update(body);
  languages.push({ code, short: dict["_meta.short"] || code.toUpperCase(), name: dict["_meta.name"] || code, published });

  if (!CHECK_ONLY) {
    const out = [
      `/* AUTO-GENERATED by scripts/build-locales.js from data/locales/${code}.json — edit the JSON, then run \`npm run build\`. */`,
      "window.I18N_LOCALES = window.I18N_LOCALES || {};",
      `window.I18N_LOCALES[${JSON.stringify(code)}] = ${body};`,
      "",
    ].join("\n");
    fs.writeFileSync(path.join(DIR, `${code}.js`), out);
  }
});

if (failed) process.exit(1);

if (!CHECK_ONLY) {
  const version = hash.digest("hex").slice(0, 10);
  const block = [
    "/* LANGUAGES START — written by scripts/build-locales.js; do not edit by hand. */",
    `  var VERSION = ${JSON.stringify(version)};`,
    "  var LANGUAGES = [",
    languages
      .map((lang) => `    { code: ${JSON.stringify(lang.code)}, short: ${JSON.stringify(lang.short)}, name: ${JSON.stringify(lang.name)}, published: ${lang.published} }`)
      .join(",\n"),
    "  ];",
    "  /* LANGUAGES END */",
  ].join("\n");
  const source = fs.readFileSync(I18N_JS, "utf8");
  const pattern = /\/\* LANGUAGES START[\s\S]*?\/\* LANGUAGES END \*\//;
  if (!pattern.test(source)) {
    console.error("[locales] js/i18n.js is missing its LANGUAGES START/END markers");
    process.exit(1);
  }
  fs.writeFileSync(I18N_JS, source.replace(pattern, () => block));
  const published = languages.filter((lang) => lang.published).map((lang) => lang.code);
  console.log(`[locales] Wrote ${languages.length} dictionaries (version ${version}); published: ${published.join(", ")}`);
}
